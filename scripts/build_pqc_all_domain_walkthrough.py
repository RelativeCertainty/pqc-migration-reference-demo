def expand_row_heights(data, response_cells):
    """Preserve styles/layout and reserve readable height for filled response cells.

    This is a focused extension of the existing XML template filler, explicitly
    authorized for these copies; no new workbook library is introduced.
    """
    cells, paths, parts = workbook(data)
    for sheet, addresses in cells.items():
        if sheet not in {"Start here", "Five questions", "Products & deployments", "Version & return record"}:
            continue
        root = ET.fromstring(parts[paths[sheet]])
        for row in root.find(f"{{{NS}}}sheetData"):
            row_no = int(row.get("r"))
            texts = [text for address, text in addresses.items() if address in response_cells.get(sheet, {}) and int(''.join(filter(str.isdigit, address))) == row_no]
            if not texts:
                continue
            # Product columns are narrower; statement rows span merged columns.
            chars = 27 if sheet == "Products & deployments" else 92
            lines = max(sum(max(1, (len(line) + chars - 1) // chars) for line in text.splitlines()) for text in texts)
            minimum = 18 * lines + 12
            if minimum > float(row.get("ht", "15")):
                row.set("ht", str(min(300, minimum)))
                row.set("customHeight", "1")
        parts[paths[sheet]] = ET.tostring(root, encoding="utf-8", xml_declaration=True)
    output = BytesIO()
    with ZipFile(output, "w", ZIP_DEFLATED) as z:
        for name, content in parts.items():
            z.writestr(name, content)
    return output.getvalue()


def mark_synthetic_print_copy(data):
    """Mark every printed page without altering immutable questionnaire cells."""
    _, paths, parts = workbook(data)
    for sheet, path in paths.items():
        root = ET.fromstring(parts[path])
        margins = root.find(f"{{{NS}}}pageMargins")
        if margins is not None:
            margins.set("top", "0.65")
            margins.set("bottom", "0.65")
            margins.set("header", "0.2")
            margins.set("footer", "0.2")
        header_footer = root.find(f"{{{NS}}}headerFooter")
        if header_footer is None:
            header_footer = ET.SubElement(root, f"{{{NS}}}headerFooter")
        # Populate and enable every variant. LibreOffice can otherwise omit the
        # odd-only header on inherited first/even page styles despite false flags.
        header_footer.set("differentFirst", "true")
        header_footer.set("differentOddEven", "true")
        for child in list(header_footer):
            header_footer.remove(child)
        for variant in ("odd", "even", "first"):
            ET.SubElement(header_footer, f"{{{NS}}}{variant}Header").text = '&C&"Calibri,Bold"&11&K9C1C1CSYNTHETIC TRAINING COPY — DO NOT EMAIL'
            ET.SubElement(header_footer, f"{{{NS}}}{variant}Footer").text = '&L&"Calibri,Regular"&9Fictional training inputs only&C&"Calibri,Bold"&9DO NOT EMAIL&R&"Calibri,Regular"&9Page &P of &N'
        parts[path] = ET.tostring(root, encoding="utf-8", xml_declaration=True)
    output = BytesIO()
    with ZipFile(output, "w", ZIP_DEFLATED) as archive:
        for name, content in parts.items():
            archive.writestr(name, content)
    return output.getvalue()


def workspace_purpose(uses):
    """Map a primary raw use to the existing coarse workspace categories.

    Preserve all original purposes in technicalBasis. Do not invent a signing
    purpose for generic custodians or application-signature records whose
    business operation is unspecified by the closed fixture.
    """
    if not uses:
        return "context"
    use = uses[0]
    purpose, role = use["purpose"], use.get("role", "")
    if purpose in {"key_establishment", "authentication"}:
        return purpose
    if purpose in {"data_encryption", "key_wrapping"}:
        return "data_protection"
    if purpose == "digital_signature":
        if role in {"code_signer", "firmware_verifier"}:
            return "software_signing"
        if role in {"certificate_issuer", "peer_authentication", "token_issuer", "credential_issuer", "dnssec_signer"}:
            return "authentication"
    return "context"


def make_bundle(page, records, *, suffix, observed_at, label):
    raw = copy.deepcopy(page["payload"])
    raw["records"] = copy.deepcopy(records)
    if "content_sha256" in raw:
        raw["content_sha256"] = extended_page_digest(raw)
    normalized = normalize_page(page["kind"], raw, tenant_id="synthetic-enterprise", source_instance_id=page["source"], observed_at=observed_at)
    family = KIND_TO_FAMILY.get(page["kind"], page["kind"])
    bundle = dict(schemaVersion="pqc.workspace.registered-source-bundle.v1", synthetic=True,
        tenantId="synthetic-enterprise", familyId=family, sourceInstanceId=page["source"], sourceLabel=label,
        observedAt=observed_at, collectedAt=AS_OF, normalizerVersion=NORMALIZER,
        rawSourceSha256=sha(canonical(raw)), rawSource=raw, records=normalized)
    data = encoded(bundle)
    assert len(data) <= 32768 and 0 < len(normalized) <= 32
    return f"bundles/{family}-{suffix}.json", bundle


def technical_position(family, name, bundle):
    """Produce a bounded descriptive position only from that family's record.

    This is scenario-authoring input for review, not a pre-admitted finding.
    Business hypotheses are separately qualified rather than disguised as
    observations. Cross-family links still require the application's review.
    """
    observation=bundle["records"][0]; facts=observation["facts"]
    uses=facts.get("cryptographic_uses",[])
    if family=="certificate-lifecycle":
        uses=[dict(purpose="authentication",role="certificate signature",algorithm=facts.get("signature_algorithm"),basis=observation["assertion_kind"])]
    elif family=="traffic-termination":
        uses=[dict(purpose="key_establishment",role="transport key exchange",algorithm=facts.get("key_exchange_group"),basis=observation["assertion_kind"]),
            dict(purpose="authentication",role="certificate signature",algorithm=facts.get("certificate_signature_algorithm"),basis=observation["assertion_kind"])]
    selected=[]
    for key,value in facts.items():
        if key in {"native_id","name"} or key.endswith("_ref") or isinstance(value,(dict,list)) or value is None or key.endswith(("_present","_basis","_key_bits","_protocol_version","_trust_until","_algorithm")):
            continue
        selected.append((key,value))
        if len(selected)==3:break
    readable="; ".join(f"{key.replace('_',' ')} = {str(value).lower() if isinstance(value,bool) else value}" for key,value in selected)
    use_text="; ".join(f"{u['role'].replace('_',' ')}: {u.get('algorithm') or 'unknown algorithm'} ({u.get('basis') or 'unknown basis'})" for u in uses)
    finding=f"Selected {name.lower()} record {facts['native_id']} reports {readable or 'context references only'}."
    finding += " Modeled cryptographic uses: " + use_text + "." if uses else " It contains no asserted cryptographic-use observation; it supplies context, not a direct algorithm-exposure finding."
    finding += " These are closed synthetic record assertions, not live enterprise verification."
    if family=="traffic-termination":
        finding=BUSINESS["area-03"]["finding"]+" The supporting rows separately retain key-exchange and certificate-authentication algorithms."
        scenario=BUSINESS["area-03"]["scenario"]
    elif not uses:
        scenario=f"Incorrect, stale or incomplete {name.lower()} context can misdirect cohort selection or create unsupported readiness claims. This source alone establishes no cryptographic algorithm exposure."
    elif all(u["purpose"]=="data_encryption" and (u.get("algorithm") or "").startswith("AES-256") for u in uses):
        scenario=f"The selected {name.lower()} record describes AES-256 data encryption. That fact alone does not establish quantum-vulnerable data encryption; investigate the separate key-wrapping, transport and recovery dependencies before drawing a stronger conclusion."
    elif any("MLKEM" in (u.get("algorithm") or "") or "ML-KEM" in (u.get("algorithm") or "") for u in uses):
        scenario=f"Hybrid establishment appears in the selected {name.lower()} reference record. Its limited observation scope does not establish PQC authentication, all-client interoperability or deployment-wide readiness."
    else:
        scenario=f"The selected {name.lower()} source describes {use_text}. If the relying business service depends on these uses over the stated lifetime, separately investigate compatibility, exposure and recovery; no whole-service PQC-readiness claim follows."
    return dict(conclusion=finding,scenario=scenario,sourceFacts=[dict(field=k,value=v) for k,v in selected],uses=uses)


def build(output: Path, *, with_forms=True):
    output = output.absolute()
    if any(p.is_symlink() for p in (output, *output.parents)):
        raise ValueError("symlink_output_denied")
    if output.exists():
        raise ValueError("create_only_output_exists")
    catalog = json.loads(CATALOG.read_text())
    definitions = json.loads((FIXTURES / "catalog.json").read_text())
    crosswalk = json.loads(CROSSWALK.read_text())
    estate = generate_estate(seed=7, application_count=12, source_scope="all")
    families = {row["id"]: row for row in catalog["source_families"]}
    forms = {row["familyId"]: row for row in definitions["forms"]}
    assert len(forms) == len(families) == 27 and set(forms) == set(families)
    assert all(forms[f]["domainId"] == families[f]["area_ref"] for f in forms)
    output.mkdir(mode=0o700, parents=True)
    files = {}
    def store(name, value, raw=False):
        data = value if raw else encoded(value)
        new(output / name, data)
        files[name] = dict(name=name, sha256=sha(data), bytes=len(data))
    registry = []
    bundle_refs = {f: [] for f in families}
    selected_bundles={}
    pages = {KIND_TO_FAMILY.get(p["kind"], p["kind"]): p for p in reversed(estate["pages"])}
    for family, profile in families.items():
        page = pages[family]
        row = copy.deepcopy(page["payload"]["records"][0])
        observed = "2026-09-14T10:00:00Z"
        if family == "vendor-assurance":
            observed = "2026-07-01T10:00:00Z"
        if family == "cmdb":
            row.update(name="Synthetic Client Portal", owner_id="synthetic-service-team", business_service_id="service-001", criticality="high", confidentiality_until="2033-09-16")
        if family == "traffic-termination":
            row.update(hostname="portal-east.example", key_exchange_group="X25519MLKEM768", protocol="TLSv1.3", evidence_basis="configured")
