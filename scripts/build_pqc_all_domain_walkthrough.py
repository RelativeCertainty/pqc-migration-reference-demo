def audit_layout(inputs: Path):
    """Conservative line-budget check, supplementary to actual office rendering."""
    scenario=json.loads((inputs/"scenario.json").read_text())
    specs={row["familyId"]:row for row in json.loads((FIXTURES/"catalog.json").read_text())["forms"]}
    audited=[]
    for case in scenario["cases"]:
        spec=specs[case["familyId"]]
        data=(inputs/case["formPath"]).read_bytes()
        cells,paths,parts=workbook(data)
        selected={"Start here":list(spec["respondentCells"].values()),"Five questions":[q[k] for q in spec["questions"] for k in ("status","text","reference","attribution","followUp")],
            "Products & deployments":[f"{chr(65+c)}{r+4}" for r in range(len(case["products"])) for c in range(8)],"Version & return record":[spec["coordinatorCell"]]}
        checked=[]
        for sheet,addresses in selected.items():
            row_heights={int(row.get("r")):float(row.get("ht","15")) for row in ET.fromstring(parts[paths[sheet]]).find(f"{{{NS}}}sheetData")}
            width=27 if sheet=="Products & deployments" else 92
            for address in addresses:
                text=cells[sheet].get(address,"")
                if not text:continue
                row=int(''.join(filter(str.isdigit,address)))
                required=18*sum(max(1,(len(line)+width-1)//width) for line in text.splitlines())+12
                checked.append(dict(sheet=sheet,cell=address,characters=len(text),estimatedMinimumHeightPoints=required,actualHeightPoints=row_heights[row],passes=row_heights[row]>=required))
        audited.append(dict(familyId=case["familyId"],filename=case["formPath"],sha256=sha(data),cells=checked,passes=all(row["passes"] for row in checked)))
    return dict(schemaVersion="pqc.walkthrough.workbook-layout-audit.v1",synthetic=True,forms=27,checks=audited,passes=all(row["passes"] for row in audited),
        boundary="Heuristic line-height budget, not an office renderer or proof of pixel-perfect layout. Render representative long forms before delivery.")


